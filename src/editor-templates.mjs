export function getEditorTemplates(references = []) {
  const readyReferences = new Map(
    references
      .filter((reference) => reference.analysisStatus === "ready")
      .map((reference) => [reference.id, reference]),
  );
  return builtInTemplates.map((template) => {
    const reference = template.referenceId
      ? readyReferences.get(template.referenceId)
      : null;
    return {
      ...template,
      analysis: reference?.analysis || null,
      referenceTitle: reference?.title || null,
      available: !template.upcoming,
    };
  });
}

export function getEditorTemplate(id, references = []) {
  return getEditorTemplates(references).find((template) => template.id === id)
    || getEditorTemplates(references)[2];
}
